/** 気性の値域（正典 §5.2 の写し） */
export const TEMPER_BOUNDS = { min: 0, max: 100 } as const;

/**
 * 気性の下限＝**誕生時の気性 × この比率**（★較正定数・D-049）。
 *
 * 【★較正の根拠（V-15: キャリア中盤の集団SD ≥ 誕生時SD の 50%）】
 *   400頭・バランス型・週169（78〜260の中点）・イベント有で掃引
 *   （★確定値 0.60 は 1,800頭で再測: 中盤 60.8% / 259週 60.0%）:
 *
 *     0.50 → 52.2%（漸近値 50% ＝ **ゲートちょうど・余裕ゼロ**）
 *     0.55 → 56.2%（漸近値 55%）
 *     ★0.60 → 60.5%（漸近値 60% ＝ **どの方針でも 10pt の余裕**）
 *     0.65 → 65.1%（漸近値 65%。ただし §7.2 が動かせる幅が 35% まで減る）
 *
 【★V-15 が両側になりました（2026-08-11・Q-P3-27 の裁定）】
 *   当初 V-15 は①（SD ≥ 50%）だけで、**最大余裕を与える状態が「比率 1.0 ＝
 *   気性の変化が一度も起きない世界」**でした。V-12a（上限のみ → F≒0 ＝ 近交が
 *   一度も働かない世界）と同じ型で、**機構を止めるとゲートが最もよく通る**形です。
 *
 *   → ② **キャリアを通じた平均低下 ≥ 15%** が追加され、上下から挟まれました。
 *
 *   両側での掃引（400頭・イベント有。①は最悪方針、②も最悪方針で読んだ場合）:
 *
 *     比率    ①最悪SD比  余裕      ②最悪低下  余裕
 *     0.50     50.1%   +0.1pt     17.3%   +2.3pt
 *     0.55     55.0%   +5.0pt     16.6%   +1.6pt   ← 最小余裕が最大
 *     ★0.60    59.9%   +9.9pt     15.9%   +0.9pt   ← 確定値
 *     0.65     64.9%  +14.9pt     15.0%   +0.0pt
 *     0.70     69.9%  +19.9pt     14.0%   −1.0pt FAIL
 *
 *   ★**窓は [0.50, 0.65]** です。0.60 は**どちらの読みでも②を満たします**
 *     （代表方針 balanced なら 35.8%、最悪方針 neglect でも 15.9%）。
 *   ★ただし「②を最悪方針で読む」なら最小余裕が最大なのは 0.55 です（照会 Q-P3-28）。
 *
 * 【★SD比は比率 r に漸近します（実測で確認）】
 *   全馬が下限 r×誕生値 に収束するので、SD → r × 誕生時SD。
 *   r=0.60 の推移: 104週 82.8% → 130週 66.3% → 169週 60.5% → 259週 59.8%
 *   → **「バランス型でたまたま通った」ではなく、どの方針でも下回らない**のが 0.60 の根拠です。
 *
 * ⚠️ **1行で書くこと**（変異試験は行単位で宣言を置換するため）
 */
// prettier-ignore
export const TEMPER_FLOOR_RATIO = 0.6;

/**
 * その馬の気性の下限。★**誕生時の値からしか決まりません**。
 *
 * ★現在値から決めてはいけません。現在値から決めると下限も一緒に下がり続け、
 *   結局 0 まで落ちます（是正前と同じことが、遅くなるだけで起こります）。
 */
export function temperFloor(birthTemper: number): number {
  return birthTemper * TEMPER_FLOOR_RATIO;
}

/**
 * 気性を1回ぶん動かす。**残り幅に比例**させるので、下限にも上限にも張り付きません。
 *
 * ```
 * 下げる: next = temper + delta × (temper - floor) / (birth - floor)
 * 上げる: next = temper + delta × (100 - temper) / (100 - birth)
 * ```
 *
 * ★`headroom`（成長）と同じ形です。**残りが少ないほど動きにくい**ので、
 *   下限に**漸近**しますが到達はしません。
 *
 * ★誕生時が下限と等しい（気性0）馬は下がりません。
 *   誕生時が上限（気性100）の馬は上がりません。**0 除算をここで閉じます。**
 */
export function applyTemperDelta(
  temper: number,
  delta: number,
  birthTemper: number,
): number {
  if (delta === 0) return temper;
  const floor = temperFloor(birthTemper);

  if (delta < 0) {
    const span = birthTemper - floor;
    if (span <= 0) return temper; // ★気性 0 の馬。下げようがない
    const room = temper - floor;
    if (room <= 0) return temper;
    const next = temper + delta * (room / span);
    // ★数値誤差で下限を割らせない
    return next < floor ? floor : next;
  }

  const span = TEMPER_BOUNDS.max - birthTemper;
  if (span <= 0) return temper; // ★気性 100 の馬。上げようがない
  const room = TEMPER_BOUNDS.max - temper;
  if (room <= 0) return temper;
  const next = temper + delta * (room / span);
  return next > TEMPER_BOUNDS.max ? TEMPER_BOUNDS.max : next;
}
