    /** ★詰め始める残り距離（m） */
    readonly fromMetersLeft: number;
    /** ★いちばん近づく残り距離（m） */
    readonly toMetersLeft: number;
    /** ★いちばん近いときの前方距離（m）。`camera.backM` からここまで滑らかに詰める */
