/**
 * ★勝負服の色替えから**肌を外す**ための色判定
 *
 * 【なぜ要るか（2026-08-21・オーナー評「騎手の肌の色が白いのがいる」）】
 *   勝負服の色替えは「兜・上着・鞍布の窓の中で、**彩度が低く暗すぎない**画素」を塗ります。
 *   明るい肌（例 231/180/148・彩度差 83）は彩度で弾かれますが、
 *   ★**陰になった肌**（例 150/130/120・彩度差 30）は**その条件を通ってしまいます。**
 *   首すじ・手の甲・頬がここに入り、淡い勝負服だと**白く塗り潰されます。**
 *
 * 【なぜこの形で判定できるか】
 *   素材の勝負服は**無彩色の灰／白**で作らせています（生成プロンプトで明示）。
 *   したがって窓の中に **R > G > B** の肌色相があれば、それは**肌**です。
 *
 * ⚠️ ★これは「顔の検出」ではありません。**塗ってはいけない色相を外すだけ**です。
 *    馬体（鹿毛）も R>G>B ですが、馬体は色替えの窓の外なので影響しません。
 */
export function isSkinTone(r: number, g: number, b: number): boolean {
  if (!(r > g && g > b)) return false;
  // 真っ黒に近い影は対象外（塗っても白くならないので外す必要がない）
  if (r < 60) return false;
  return r - g >= 8 && r - b >= 18;
}

/**
 * ★毛色フィルタで脱色された肌を、**元の色で塗り直してよいか**
 *
 * 【なぜ別の判定が要るか（2026-08-21）】
 *   毛色バリエーションは**素材全体に CSS フィルタ**を掛けます。芦毛は `saturate(0.12)` なので、
 *   ★**騎手ごと脱色されます。** 勝負服は別のオーバーレイなので色が残り、
 *   結果として**肌だけグレー**になります（オーナー評「黄色の服の騎手の肌の色がグレー」）。
 *
 *   → オーバーレイに**肌の画素を元の色のまま載せて**、フィルタの上から塗り直します。
 *
 * 【★`isSkinTone` より狭くする理由】
 *   `isSkinTone` は「**塗ってはいけない**」を判定するので広めで安全です。
 *   こちらは「**塗り直す**」なので、**馬体を巻き込むと毛色バリエーションが壊れます。**
 *
 *   実測（`horse-jockey-side-v7-pose01.png` の R>G>B 画素の分布）:
 *     r−g  0〜10 … (141,136,132) ほぼ無彩色＝勝負服・馬具
 *     r−g 10〜30 … (121,107,95) (104,79,62) ＝**肌**
 *     r−g 30〜90 … (87,52,30)〜(169,87,33) ＝**鹿毛の馬体**
 *   → **r−g が 55 を超えるものは馬体**として除外します。
 *
 * ⚠️ ★色だけでは分けきれません（明るい肌は r−g 45〜51 で馬体の帯と重なる）。
 *    **呼び出し側で「騎手の窓の中だけ」に限る**こと。窓の中に居る馬体は
 *    たてがみ（黒・`r < 85` で除外）と首（鹿毛・`r−g > 55` で除外）だけです。
 */
export function isSkinRepaint(r: number, g: number, b: number): boolean {
  if (!(r > g && g > b)) return false;
  if (r < 85) return false;                    // 黒いたてがみ・濃い影は対象外
  if (r - g < 8) return false;                 // 無彩色（勝負服・鞍布）は対象外
  /**
   * ★**差ではなく比**で分けます。
   *   ⚠️ 差（r−g）で分けようとして失敗しました。**明るい肌 (231,180,148) は r−g=51、
   *      濃い鹿毛 (87,52,30) は r−g=35** で、帯が重なって分離できません。
   *   比なら明確に分かれます（実測）:
   *     肌   g/r 0.78〜0.87 ／ b/r 0.63〜0.80
   *     鹿毛 g/r 0.51〜0.60 ／ b/r 0.30〜0.35
   */
  return g / r >= 0.72 && b / r >= 0.55;
}
