/**
 * ★勝負服の色替えから**肌を外す**ための色判定
 *
 * 【なぜ要るか（2026-08-21・オーナー評「騎手の肌の色が白いのがいる」）】
 *   勝負服の色替えは「兜・上着・鞍布の窓の中で、**彩度が低く暗すぎない**画素」を塗ります。
 *   明るい肌（例 231/180/148・彩度差 83）は彩度で弾かれますが、
 *   ★**陰になった肌**（例 150/130/120・彩度差 30）は**その条件を通ってしまいます。**
 *   首すじ・手の甲・頬がここに入り、淡い勝負服だと**白く塗り潰されます。**
 *
 * 【なぜこの形で判定できるか】
 *   素材の勝負服は**無彩色の灰／白**で作らせています（生成プロンプトで明示）。
 *   したがって窓の中に **R > G > B** の肌色相があれば、それは**肌**です。
 *
 * ⚠️ ★これは「顔の検出」ではありません。**塗ってはいけない色相を外すだけ**です。
 *    馬体（鹿毛）も R>G>B ですが、馬体は色替えの窓の外なので影響しません。
 */
export function isSkinTone(r: number, g: number, b: number): boolean {
  if (!(r > g && g > b)) return false;
  // 真っ黒に近い影は対象外（塗っても白くならないので外す必要がない）
  if (r < 60) return false;
  return r - g >= 8 && r - b >= 18;
}

