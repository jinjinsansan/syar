/**
 * ★id を ★**コードポイントの順**で比べる（★`localeCompare` を使わない）。
 *
 * @returns ★`a < b` なら負、★`a > b` なら正、★同じなら 0
 */
export function compareIds(a: string, b: string): number {
  if (a < b) return -1;
  if (a > b) return 1;
  return 0;
}
