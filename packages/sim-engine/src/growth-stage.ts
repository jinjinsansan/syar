/**
 * ★**育った実感の 4 層のうち「成長」— 何が伸びたか**（★**D-116 ②③④**・2026-09-19）
 *
 * 【★なぜ段階と別の場所にあるか】
 *   ★**成長段階**（まだ幼い／…／円熟期）は ★**一生の話**なので `@star/scheduler` にあります
 *   （★`LIFECYCLE_WEEKS` を引くため。★`@star/sim-engine` は依存ゼロで scheduler を引けません）。
 *   ★**こちら**は ★**能力の話**なので、★`AbilityKey` を持つこの層にあります。
 *   ⚠️ ★**数を写して両方に置く、はしません**（D-052）。
 *
 * 【★D-116 ② — 数値・割合・ランクを出さない】
 *   ⚠️ ★返すのは ★**能力の名前**だけです。★「`stamina` +3」「成長度 73%」は不可。
 */

import type { AbilityKey } from './types.js';

/**
 * ★**この幅より小さい変化は言わない**（★D-116 ③・較正定数）。
 *
 * 【★なぜ閾値が要るのか】★D-116 ③ より
 *   > 「★閾値を設け、小さい変化は出さない。★**毎週必ず何かが出る形にしない**」
 *   > 「★出れば出るほど**符号列が積み上がる**」
 *
 *   ⚠️ ★毎週「スタミナが伸びた」と言い続けると、★**十分長く観測すれば
 *      「どの能力が何回伸びたか」が分かり**、★`stats` の粗い順序を与えます
 *      （★D-114 が「代償を承知で採る」と書いた漏れを、★**わざわざ広げる**ことになります）。
 *
 * ⚠️ ★**値そのものをゲートにしません**。★動かすと「どれくらい伸びたら言うか」だけが変わり、
 *    ★能力・着順・成長そのものには入りません。
 */
export const GROWTH_TELL_MIN = 8;

/** ★能力 → 画面に出す言葉（★§5 の能力名の言い換え。★数値は出さない） */
export const ABILITY_GROWTH_LABEL: Readonly<Record<AbilityKey, string>> = {
  sp: '速さ',
  st: '粘り',
  pw: '力強さ',
  gt: '折り合い',
  iq: '賢さ',
};

/**
 * ★**前と今を比べて、言えることだけを言う**（★D-116 ②③④）。
 *
 * ⚠️ ★**数値・割合・ランクを返しません**（D-116 ②）。★返すのは ★**能力の名前**だけで、
 *    ★言葉に組み立てるのは画面の仕事です。
 * ⚠️ ★**伸びだけを見ます**。★下がった能力は言いません
 *    — ★§7.5 の恒久ダメージは ★**「状態」でも「成長」でもなく、物語の層**の話です（D-116 ④）。
 * ⚠️ ★**閾値に届かなければ空**を返します。★**毎週必ず何かが出る形にしません**（D-116 ③）。
 *
 * ★`before` / `after` … ★同じ馬の `stats`（★**呼ぶ側が持っているもの**）。
 *   ⚠️ ★この関数は ★**`potential` を受け取りません** — ★開放率を作れないようにするためです。
 */
export function growthTellsOf(
  before: Readonly<Record<AbilityKey, number>>,
  after: Readonly<Record<AbilityKey, number>>,
  minDelta = GROWTH_TELL_MIN,
): AbilityKey[] {
  const keys: AbilityKey[] = ['sp', 'st', 'pw', 'gt', 'iq'];
  const out: AbilityKey[] = [];
  for (const k of keys) {
    const d = after[k] - before[k];
    if (d >= minDelta) out.push(k);
  }
  return out;
}
