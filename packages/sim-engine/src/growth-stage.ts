import type { AbilityKey } from './types.js';

/**
 * ★**この幅より小さい変化は言わない**（★D-116 ③・較正定数）。
 *
 * 【★なぜ閾値が要るのか】★D-116 ③ より
 *   > 「★閾値を設け、小さい変化は出さない。★**毎週必ず何かが出る形にしない**」
 *   > 「★出れば出るほど**符号列が積み上がる**」
 *
 *   ⚠️ ★毎週「スタミナが伸びた」と言い続けると、★**十分長く観測すれば
 *      「どの能力が何回伸びたか」が分かり**、★`stats` の粗い順序を与えます
 *      （★D-114 が「代償を承知で採る」と書いた漏れを、★**わざわざ広げる**ことになります）。
 *
 * ⚠️ ★**値そのものをゲートにしません**。★動かすと「どれくらい伸びたら言うか」だけが変わり、
 *    ★能力・着順・成長そのものには入りません。
 *
 * 【✅ ★**2026-09-19・GB-1 ④ で 8 → 13**（★オーナー決定）】
 *   ★オーナーの決め方は ★**「閾値から決めず、一生で何回 言うかから決める。推しは 20〜30 回」**。
 *   ✔ ★測りました（`apps/cli/src/growth-tell-frequency.ts`・★1,200 頭 ＝ 150 × 8 シード）:
 *
 *   | 幅 | ★累積 平均 | 20〜30 回に収まる馬 | 週次 平均 |
 *   |---|---|---|---|
 *   | **8**（旧） | **37.6 回** | **2%** | 8.8 回 |
 *   | 11 | 28.4 | 79% | 2.6 |
 *   | 12 | 26.3 | 96% | 1.8 |
 *   | ✅ **13** | ★**24.4 回** | ★**98%** | 1.2 |
 *   | 16 | 20.2 | 68% | 0.3 |
 *   | 20 | 16.4 | 1% | 0.0 |
 *
 *   → ★**13 が、平均も（帯の真ん中 25 に最も近い）★収まる割合も（98%）最良**でした。
 *   ✔ ★**一生で 1 度も言われない馬は 0%**（★どの幅でも）。★いちばん悪い体験は起きません。
 */
export const GROWTH_TELL_MIN = 13;

/** ★能力 → 画面に出す言葉（★§5 の能力名の言い換え。★数値は出さない） */
export const ABILITY_GROWTH_LABEL: Readonly<Record<AbilityKey, string>> = {
  sp: '速さ',
  st: '粘り',
  pw: '力強さ',
  gt: '折り合い',
  iq: '賢さ',
};

/**
 * ★**前と今を比べて、言えることだけを言う**（★D-116 ②③④）。
 *
 * ⚠️ ★**数値・割合・ランクを返しません**（D-116 ②）。★返すのは ★**能力の名前**だけで、
 *    ★言葉に組み立てるのは画面の仕事です。
 * ⚠️ ★**伸びだけを見ます**。★下がった能力は言いません
 *    — ★§7.5 の恒久ダメージは ★**「状態」でも「成長」でもなく、物語の層**の話です（D-116 ④）。
 * ⚠️ ★**閾値に届かなければ空**を返します。★**毎週必ず何かが出る形にしません**（D-116 ③）。
 *
 * ★`before` / `after` … ★同じ馬の `stats`（★**呼ぶ側が持っているもの**）。
 *   ⚠️ ★この関数は ★**`potential` を受け取りません** — ★開放率を作れないようにするためです。
 *
 * 【🔴 ★**`before` は「前に言ったときの `stats`」です**（★**累積**・GB-1 ④・オーナー決定）】
 *   ★**「先週の `stats`」ではありません。**
 *   ✔ ★測りました: ★週次だと ★**一生に 1.2 回**しか言われません（★幅 13）。
 *     ★オーナーの推し **20〜30 回**には ★**どの幅でも届きません**（★幅 8 でも 8.8 回）。
 *   → ★**言った週の `stats` を憶えておき、★次はそれと比べます。**
 *     ★言わなかった週では ★**基準を更新しません**（★更新したら週次と同じものになります）。
 *
 *   ⚠️ 🔴 ★**代償を承知で採っています**（★オーナー判断 C-4 の表の右側）:
 *     ★**長く観測すると、能力値を 0.8% の精度で復元できます**（★D-114 が隠したもの）。
 *     ★**回数を 20〜30 に絞ることが、そのまま漏れを絞ること**です
 *     （★一生 182 週で毎週 言えば 182 個の符号。★24 回ならその 1/7.6）。
 *
 *   ⚠️ ★**基準を持つのは呼ぶ側**です（★この関数は状態を持ちません）。
 *     ★配線するときは ★**「前に言ったときの `stats`」を DB に残すこと**（★未実装）。
 */
export function growthTellsOf(
  before: Readonly<Record<AbilityKey, number>>,
  after: Readonly<Record<AbilityKey, number>>,
  minDelta = GROWTH_TELL_MIN,
): AbilityKey[] {
  const keys: AbilityKey[] = ['sp', 'st', 'pw', 'gt', 'iq'];
  const out: AbilityKey[] = [];
  for (const k of keys) {
    const d = after[k] - before[k];
    if (d >= minDelta) out.push(k);
  }
  return out;
}
