/**
 * ★ドットの数字（5×7）
 *
 * 【なぜ作り直したか】
 *   最初 **3×5** で描き、オーナーの評価は「まだ頑張って欲しい／ゼッケンで幻滅する」でした。
 *   ★3×5 は**字が成立する最小**であって、**読みやすい形ではありません**。
 *     数字の太さが1画素しかないので、色の布に乗せると線が消えかけます。
 *
 *   → **5×7** にしました。縦棒が2画素になり、**印刷された数字の見え方**に近づきます。
 *     16bit 期のスポーツゲームのスコア表示がこの粒度です（アートバイブル §7 の参照）。
 *
 * 【★縁取りを付ける】
 *   実際のゼッケンは**布に印刷された数字**で、布の陰影の上に乗ります。
 *   縁取りが無いと「後から描いた」ように見えるので、**1画素の暗い縁**を付けられるようにします。
 *
 * 【★整数倍で拡大すること】
 *   5×7 を ×2 なら 10×14。**非整数倍にすると画素が割れます**（D-058 の禁止事項）。
 */

/**
 * 0〜9 を 5×7 で。
 *
 * ★**線の太さを全部1画素で揃えます。**
 *   前の字形は 1画素の線と2画素の線が混在しており、
 *   「フォント感が揃っていない」と指摘されました。★そのとおりで、
 *   **同じ書体に見えるかどうかは、線の太さが揃っているかで決まります。**
 *   拡大は整数倍なので、×2 なら全部2画素、×3 なら全部3画素になります。
 *
 * ★字幅も全桁 5 で揃えます（1 だけ細い、をやらない）。
 */
const GLYPHS = {
  0: ['01110', '10001', '10001', '10001', '10001', '10001', '01110'],
  1: ['00100', '01100', '00100', '00100', '00100', '00100', '01110'],
  2: ['01110', '10001', '00001', '00010', '00100', '01000', '11111'],
  3: ['11111', '00010', '00100', '00010', '00001', '10001', '01110'],
  4: ['00010', '00110', '01010', '10010', '11111', '00010', '00010'],
  5: ['11111', '10000', '11110', '00001', '00001', '10001', '01110'],
  6: ['00110', '01000', '10000', '11110', '10001', '10001', '01110'],
  7: ['11111', '00001', '00010', '00100', '01000', '01000', '01000'],
  8: ['01110', '10001', '10001', '01110', '10001', '10001', '01110'],
  9: ['01110', '10001', '10001', '01111', '00001', '00010', '01100'],
};

export const GLYPH_W = 5;
export const GLYPH_H = 7;
/** 字間（画素） */
const TRACK = 1;

/**
 * 数字の並びを「塗る画素の座標」の配列にする。
 * ★描画そのものはしません（この層はレンダラを知らない・§12.8 と同じ考え方）。
 */
export function digitPixels(text, scale = 1) {
  const out = [];
  let ox = 0;
  for (const ch of String(text)) {
    const g = GLYPHS[ch];
    if (g === undefined) throw new Error(`描けない文字です: ${ch}`);
    for (let y = 0; y < GLYPH_H; y += 1) {
      for (let x = 0; x < GLYPH_W; x += 1) {
        if (g[y][x] !== '1') continue;
        // ★整数倍でのみ拡大する（画素を割らない）
        for (let dy = 0; dy < scale; dy += 1) {
          for (let dx = 0; dx < scale; dx += 1) {
            out.push([(ox + x) * scale + dx, y * scale + dy]);
          }
        }
      }
    }
    ox += GLYPH_W + TRACK;
  }
  return out;
}

/**
 * ★字の**縁**にあたる画素（上下左右に隣接し、字そのものではないところ）。
 *   布の陰影の上でも字が浮かないよう、暗い色で囲みます。
 */
export function outlinePixels(text, scale = 1) {
  const on = new Set(digitPixels(text, scale).map(([x, y]) => `${x},${y}`));
  const edge = new Set();
  for (const key of on) {
    const [x, y] = key.split(',').map(Number);
    for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) {
      const k = `${x + dx},${y + dy}`;
      if (!on.has(k)) edge.add(k);
    }
  }
  return [...edge].map((k) => k.split(',').map(Number));
}

/** 描いたときの幅（画素） */
export function textWidth(text, scale = 1) {
  const n = String(text).length;
  return (n * (GLYPH_W + TRACK) - TRACK) * scale;
}
