-- 0060: 「どの週まで配合したか」を世界に持たせる
--
-- ============================================================================
-- 🔴 【★なぜ要るか — ★引退は N 週ぶん、★誕生は 1 週ぶんでした】
--
--   ✔ ★現物（★2026-09-21 に 2 つを並べて読みました）:
--     ★`apps/worker/src/main.ts` … `advanceTrainingWeeks(client, nowMs, …)`
--         → ★`training-runner.ts` が `weeks: number[]` を貯め、
--           ★`weekIndexAt(nowMs) - 1` まで ★**何週でも**進めます。
--     ★同 `runBreedingWeek(client, nowMs, …)`
--         → ★`nowMs` から ★**1 週を出して、★その 1 週だけ**配合します。
--
--   → ★★**歳は N 週ぶん取るのに、★仔は 1 週ぶんしか生まれません。**
--     ★これは `POOL-SUPPLY` が防ごうとしたもの（★「引退だけが動き、生まれません」）の
--     ★**別の形**です。
--
--   ✔ ★**実際に 1 度 起きています**: ★2026-08-20〜09-02 の ★**13 日 停止 ＝ 78 週**。
--     ★あのとき復旧していたら、★**77 週ぶんの仔が飛んでいました**。
--
-- 【★なぜ「印」が要るのか — ★誕生の記録からは導けません】
--   ⚠️ ★「最後に生まれた仔の `birth_week`」では駄目です。
--     ★★**その週にたまたま 0 頭だった場合と、★配合していない場合を区別できません。**
--   → ★**配合した週そのものを書きます。**
--
-- 【★`null` の意味 — ★「0 週目から」ではありません】
--   🔴 ★`null` ＝ ★**一度も配合していない**（★本番はいまこれ）。
--     ★ここから 0 週目に遡って産ませると ★**260 週ぶんが一度に生まれます**。
--   → ★★**`null` のときは「いまの週だけ」**を配合し、★そこから印を始めます
--     （★`runBreedingCatchUp` の `startedFresh`）。
-- ============================================================================
begin;

alter table world_state add column if not exists last_bred_week bigint;

comment on column world_state.last_bred_week is
  '★配合を済ませた最後の週（★2026-09-21・簿 BREEDING-ONLY-ONE-WEEK-PER-CYCLE）。'
  '★ワーカーがここから `weekIndexAt(now) - 1` までを、★周の予算の範囲で追いつく。'
  '★null ＝ 一度も配合していない → ★**いまの週だけ**を配合して印を始める'
  '（★0 週目に遡らない。★遡ると数百週ぶんが一度に生まれる）。'
  '⚠️ ★「最後に生まれた仔の birth_week」では代用できない — '
  '★その週が 0 頭だった場合と、★配合していない場合を区別できないため。';

