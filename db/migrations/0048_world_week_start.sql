-- 0048: ★週の始まりの実時刻（★UI-4・`/records` の期間の絞り込み）
--
-- ============================================================================
-- 【★なぜ要るか — ★画面は「今週」を実時刻に変換できません】
--   ★`/records` は台帳（`ep_ledger` / `pp_ledger`）を ★**期間で絞ります**。
--   ★台帳が持っているのは ★**`created_at`（実時刻）**だけです。
--   ★一方「今週」は ★**ゲーム内の週**で、★開催の起点（epoch）と 1 週の長さから決まります。
--   🔴 ★画面に epoch を渡すと ★**画面が時計を持ちます**（★UI1-10 の判断）。
--   🔴 ★画面で `Date.now()` を使うのは ★**憲法 4** に反します。
--   → ★**ワーカーが「いまの週が実時刻でいつ始まったか」を書きます。**
--     ★画面は `created_at >= week_started_at` と比べるだけです。
--
-- 【★これは BT-6 ② と**同じ形**です（★ただし別件）】
--   ★裁定 `REVIEW_BET_ALLOWANCE_VERDICT_20260919.md` §3 ② が
--   ★「★SQL で『1 日』を定義しない。★ワーカーが `day_started_at` を毎周書く」と定めました。
--   ★ここは ★**「1 週」**について同じことをしています。
--   ⚠️ ★**BT-6 ② そのものは AL-11 に合流**です（★裁定 §6 の順）。★ここで `bet_allowance` は触りません。
--
-- 【⚠️ ★「今月」は書けません】
--   ★正典に ★**ゲーム内の「月」はありません**（★1 週 ＝ 4 時間・D-007）。
--   ★実時刻の暦月で切ると、★**BT-6 とまったく同じ「どの暦か決まっていない境目」**になります。
--   → ★**推測で埋めず、照会に出します**（★`QUESTIONS_UI4_20260919.md`）。
--     ★画面はいま ★**「今週」と「全期間」だけ**を出します。
-- ============================================================================

begin;

alter table world_state add column if not exists week_started_at timestamptz;

comment on column world_state.week_started_at is
  '★いまのゲーム内の週が、実時刻でいつ始まったか（★UI-4・2026-09-19）。'
  '★ワーカーが weekStartMs(weekIndexAt(now, epoch), epoch) で毎周書く（★game_week と同じ 1 本の関数から）。'
  '⚠️ ★画面はこれと created_at を比べるだけ — ★epoch も 1 週の長さも画面に渡さない（UI1-10・憲法 4）';

-- ---------------------------------------------------------------------------
-- 公開ビューに足す（★`0038` の本文を取ってきて 1 列だけ足す）
-- ---------------------------------------------------------------------------
--   ⚠️ ★**`0038` の本文を取ってきて、★1 列だけ足しています**（★思い出して書き直さない）。
--      ★`0038` は `updated_at` ではなく ★**`stale_seconds`** を返します
--      （★「古いか」の判定を画面に持たせず、★秒数だけを返す形）。★そこは 1 文字も変えていません。
create or replace view world_state_public as
select
  w.game_week,
  extract(epoch from (now() - w.updated_at))::int as stale_seconds,
  w.week_started_at
from world_state w;

comment on view world_state_public is
  '★いまの週（★UI1-10）。★画面はここだけを読む。★stale_seconds はサーバーの時計で測った「最後に書かれてからの秒数」で、'
  '★ワーカーが止まっていれば増え続ける。★閾値は画面に持たせない（★数を返すだけ）。'
  '★2026-09-19（UI-4）に week_started_at を足した — ★台帳の created_at（実時刻）を「今週」で絞るため。'
  '★epoch も 1 週の長さも出さない（★出すと画面が時計を持つ）';

grant select on world_state_public to anon, authenticated;

commit;
